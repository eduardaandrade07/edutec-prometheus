    function sphere(sx, sy, r, soft, sh, alpha) {

      if (r < 0.12 || alpha <= 0.004) {
        return;
      }

      var sharp = 1 - soft;


      if (soft > 0.02) {

        var rb = r * (1 + soft * 2.3);
        var ab = alpha * soft * 0.5;

        var gb = contexto.createRadialGradient(
          sx,
          sy,
          0,
          sx,
          sy,
          rb
        );

        gb.addColorStop(0, rgba(sh.lit, ab));
        gb.addColorStop(0.45, rgba(sh.base, ab * 0.85));
        gb.addColorStop(0.78, rgba(sh.dark, ab * 0.35));
        gb.addColorStop(1, rgba(sh.deep, 0));

        contexto.fillStyle = gb;
        contexto.beginPath();
        contexto.arc(sx, sy, rb, 0, TAU);
        contexto.fill();
      }


      if (sharp > 0.02) {

        var lx = sx - r * 0.34;
        var ly = sy - r * 0.38;
        var as = alpha * sharp;

        var g = contexto.createRadialGradient(
          lx,
          ly,
          r * 0.05,
          sx,
          sy,
          r * 1.02
        );

        g.addColorStop(0, rgba(sh.spec, as));
        g.addColorStop(0.18, rgba(sh.lit, as));
        g.addColorStop(0.52, rgba(sh.base, as));
        g.addColorStop(0.86, rgba(sh.dark, as));
        g.addColorStop(1, rgba(sh.deep, as * 0.92));

        contexto.fillStyle = g;
        contexto.beginPath();
        contexto.arc(sx, sy, r, 0, TAU);
        contexto.fill();


        if (r > 2.2) {

          contexto.strokeStyle =
            rgba(sh.lit, as * 0.3);

          contexto.lineWidth =
            Math.max(0.5, r * 0.09);

          contexto.beginPath();
          contexto.arc(
            sx,
            sy,
            r * 0.95,
            0.6,
            2.6
          );

          contexto.stroke();
        }


        if (r > 3) {

          var gs = contexto.createRadialGradient(
            lx,
            ly,
            0,
            lx,
            ly,
            r * 0.34
          );

          gs.addColorStop(
            0,
            rgba(sh.spec, as * 0.85)
          );

          gs.addColorStop(
            1,
            rgba(sh.spec, 0)
          );

          contexto.fillStyle = gs;
          contexto.beginPath();
          contexto.arc(
            lx,
            ly,
            r * 0.34,
            0,
            TAU
          );
          contexto.fill();
        }
      }
    }


