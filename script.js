  function go(page, sec) {

    if (!isSPA) {
      return false;
    }

    var target =
      document.getElementById(
        'view-' + page
      );

    if (!target) {
      return false;
    }


    views.forEach(function (v) {
      v.classList.remove('ativa');
    });

    target.classList.add('ativa');


    html.setAttribute(
      'data-area',
      page === 'home'
        ? 'home'
        : page
    );


    $$('.revelar', target)
      .forEach(function (el) {
        el.classList.remove('in');
      });


    revealIn(target);
    mountDna(target);


    if (sec) {

      setTimeout(
        function () {
          scrollToSec(sec);
        },
        70
      );

    } else {

      window.scrollTo({
        top: 0,
        behavior:
          movimentoReduzido
            ? 'auto'
            : 'smooth'
      });
    }


    $$('#linksNavegacao a')
      .forEach(function (a) {

        a.classList.toggle(
          'ativa',
          page === 'home' &&
          a.dataset.alvoSecao ===
            (sec || 'inicio')
        );
      });

    return true;
  }


