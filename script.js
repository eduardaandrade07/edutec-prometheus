    /* Cria pontos em formato de círculo */

    function ringPts(cx, cy, cz, rad, plane, segs) {

      var pts = [];

      for (var i = 0; i < segs; i++) {

        var t = i / segs * TAU;
        var c = Math.cos(t);
        var s = Math.sin(t);

        if (plane === 'xz') {
          pts.push([
            cx + c * rad,
            cy,
            cz + s * rad
          ]);
        } else if (plane === 'yz') {
          pts.push([
            cx,
            cy + c * rad,
            cz + s * rad
          ]);
        } else {
          pts.push([
            cx + c * rad,
            cy + s * rad,
            cz
          ]);
        }
      }

      return pts;
    }


    function ringRods(m, pts, wd, c, close) {

      for (
        var i = 0;
        i < pts.length - (close === false ? 1 : 0);
        i++
      ) {
        rod(
          m,
          pts[i],
          pts[(i + 1) % pts.length],
          wd,
          c
        );
      }
    }


