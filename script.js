    /* Faz a projeção dos objetos 3D na tela */

    function project(
      p,
      o,
      unit,
      cx,
      cy,
      cs,
      sn,
      ct,
      st,
      cr,
      sr
    ) {

      var x = p[0] * cs + p[2] * sn;
      var z0 = -p[0] * sn + p[2] * cs;

      var y1 = p[1] * ct - z0 * st;
      var z1 = p[1] * st + z0 * ct;

      var x2 = x * cr - y1 * sr;
      var y2 = x * sr + y1 * cr;

      var pp = o.cam / (o.cam - z1);

      return {
        x: cx + x2 * pp * unit,
        y: cy - y2 * pp * unit,
        z: z1,
        p: pp
      };
    }


